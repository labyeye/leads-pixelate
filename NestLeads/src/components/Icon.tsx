interface Props {
  name: string;
  size?: number;
  color?: string;
  style?: any;
}

export default function Icon({
  name,
  size = 20,
  color = '#000',
  style,
}: Props) {
  const LucideComponent = MAP[name];
  if (!LucideComponent) return null;
  return <LucideComponent size={size} color={color} style={style} />;
}
